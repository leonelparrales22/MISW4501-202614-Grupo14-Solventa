// ErrSourceUnavailable is returned by a RiskProfileSource that timed out,
// failed or was isolated by its circuit breaker.
var ErrSourceUnavailable = errors.New("external profile source unavailable")

// ErrCircuitOpen is returned, together with ErrSourceUnavailable, by a
// RiskProfileSource whose circuit breaker is isolating the provider: the call
// was rejected without waiting (HA-L01 reports it per source).
var ErrCircuitOpen = errors.New("external profile source isolated by its circuit breaker")

// SourcesUnavailableError is returned by a composite RiskProfileSource (the
// parallel profiling of HA-L01) when no profile can be calculated online: no
// source answered in time, or a required one did not. It wraps
// ErrSourceUnavailable, so errors.Is keeps working, and keeps the outcome of
// every source so the degraded answer can still show which one failed.
type SourcesUnavailableError struct {
	Outcomes []domain.SourceOutcome
}

func (e *SourcesUnavailableError) Error() string {
	parts := make([]string, 0, len(e.Outcomes))
	for _, o := range e.Outcomes {
		parts = append(parts, o.Source+"="+string(o.Status))
	}
	return ErrSourceUnavailable.Error() + " (" + strings.Join(parts, ", ") + ")"
}

// Unwrap lets errors.Is match ErrSourceUnavailable.
func (e *SourcesUnavailableError) Unwrap() error { return ErrSourceUnavailable }

// RiskProfileSource is an external data source (Open Finance, Open Data, KYC),
// or the parallel fan-out over them, that calculates a fresh risk profile.
type RiskProfileSource interface {
	FetchProfile(ctx context.Context, customerID string) (domain.RiskProfile, error)
}

// RiskProfileCache is Perfil_Riesgo_Cache: the last valid profile per customer.
type RiskProfileCache interface {
	// Get returns found=false on a miss; a miss is not an error.
	Get(ctx context.Context, customerID string) (profile domain.RiskProfile, found bool, err error)
	Set(ctx context.Context, profile domain.RiskProfile) error
	// Invalidate removes the cached profile (the customer is requoted);
	// removing a missing one is not an error.
	Invalidate(ctx context.Context, customerID string) error
}

// Clock allows the cached-profile age to be tested deterministically.
type Clock interface {
	Now() time.Time
}

// ErrOfferNotFound is returned by an OfferRepository that has no offer with
// the requested id.
var ErrOfferNotFound = errors.New("offer not found")

// ErrAcceptanceNotFound is returned by an AcceptanceRepository that has no
// acceptance with the requested id or for the requested offer.
var ErrAcceptanceNotFound = errors.New("acceptance not found")

// OfferRepository reads the offers generated by the rating engine
// (HU-W1.2-03).
type OfferRepository interface {
	Get(ctx context.Context, offerID string) (domain.Offer, error)
}

// AcceptanceRepository persists the offer acceptances (HU-W1.3-01). An offer
// has at most one acceptance.
type AcceptanceRepository interface {
	// Create stores the acceptance unless its offer already has one; then it
	// returns the existing acceptance and created=false.
	Create(ctx context.Context, a domain.Acceptance) (stored domain.Acceptance, created bool, err error)
	Get(ctx context.Context, acceptanceID string) (domain.Acceptance, error)
	GetByOffer(ctx context.Context, offerID string) (domain.Acceptance, error)
	Update(ctx context.Context, a domain.Acceptance) error
	// ListDue returns up to limit acceptances still registered whose next
	// attempt is due at now, oldest first.
	ListDue(ctx context.Context, now time.Time, limit int) ([]domain.Acceptance, error)
}

// Underwriter is the automatic underwriting: it accepts the risk or routes
// the request to a human decision.
type Underwriter interface {
	Decide(ctx context.Context, offer domain.Offer, acceptance domain.Acceptance) (domain.UnderwritingDecision, error)
}

// ReviewQueue is the advisor inbox of requests routed to human decision
// (HU-W1.1-02). Enqueue is idempotent by acceptance id.
type ReviewQueue interface {
	Enqueue(ctx context.Context, req domain.ReviewRequest) error
}

// IssuanceStarter starts the issuance flow of an accepted risk (charge and
// policy issuance: HU-W1.3-02, HA-D02). Start is idempotent by acceptance id.
type IssuanceStarter interface {
	Start(ctx context.Context, acceptance domain.Acceptance, offer domain.Offer) error
}

// ErrQuoteNotFound is returned by a QuoteRepository that has no quote with the
// requested id.
var ErrQuoteNotFound = errors.New("quote not found")

// ErrCustomerNotFound is returned by a CustomerRepository that has no customer
// with the requested document id.
var ErrCustomerNotFound = errors.New("customer not found")

// CustomerRepository stores the customers an advisor quotes for (HU-W1.1-01).
type CustomerRepository interface {
	// GetByDocument returns ErrCustomerNotFound when the document is unknown.
	GetByDocument(ctx context.Context, documentID string) (domain.Customer, error)
	// GetByEmail returns ErrCustomerNotFound when the email is unknown. The
	// comparison ignores case: the email is the username in the user pool.
	GetByEmail(ctx context.Context, email string) (domain.Customer, error)
	// Save creates the customer, or updates the one with the same document id
	// keeping its ID, and returns the stored customer.
	Save(ctx context.Context, c domain.Customer) (domain.Customer, error)
}

// ErrAccountExists is returned by an IdentityProvider when the email already
// has an account in the user pool.
var ErrAccountExists = errors.New("the email already has an account")

// IdentityProvider creates the accounts the insured signs in with
// (HU-M1.1-01). The user pool only accepts accounts created from the server,
// so this service decides who gets one.
type IdentityProvider interface {
	// CreateAccount creates the account with the password the person chose,
	// leaves it usable right away and returns its subject. It returns
	// ErrAccountExists when the email is taken.
	CreateAccount(ctx context.Context, email, password, fullName string) (subject string, err error)
}

// QuoteRepository persists the assisted quotes (HU-W1.1-01).
type QuoteRepository interface {
	Create(ctx context.Context, q domain.Quote) error
	// Get returns ErrQuoteNotFound when the id is unknown.
	Get(ctx context.Context, quoteID string) (domain.Quote, error)
}

// RatingInput is what the rating engine needs to price a quote.
type RatingInput struct {
	Age           int
	InsuredAmount float64
	TermMonths    int
	Profile       domain.RiskProfile
}

// Rater is the rating engine: it prices a quote from the risk profile. The
// embedded channel and the advisor share it, so both get the same price.
type Rater interface {
	Rate(ctx context.Context, in RatingInput) (domain.Rating, error)
}

// ErrContractNotFound is returned by a ContractRepository that has no
// contractual issuance for the requested policy.
var ErrContractNotFound = errors.New("contract issuance not found")

// ErrDocumentNotFound is returned by a DocumentStore that has no document
// under the requested key.
var ErrDocumentNotFound = errors.New("contract document not found")

// ErrInvalidLink is returned by a LinkSigner for a link that is malformed,
// forged or expired.
var ErrInvalidLink = errors.New("invalid or expired document link")

// CoverageActivationHandler receives the coverage activations (HU-W1.3-03).
// Receive persists the work and returns; it is idempotent by policy, so a
// redelivered event does nothing.
type CoverageActivationHandler interface {
	Receive(ctx context.Context, event domain.CoverageActivated) error
}

// ContractRepository persists the contractual issuance of each policy. A
// policy has at most one.
type ContractRepository interface {
	// Create stores the issuance unless the policy already has one; then it
	// returns the existing issuance and created=false.
	Create(ctx context.Context, c domain.ContractIssuance) (stored domain.ContractIssuance, created bool, err error)
	// Get returns ErrContractNotFound when the policy has no issuance.
	Get(ctx context.Context, policyID string) (domain.ContractIssuance, error)
	Update(ctx context.Context, c domain.ContractIssuance) error
	// ListDue returns up to limit issuances still in progress whose next
	// attempt is due at now, oldest first.
	ListDue(ctx context.Context, now time.Time, limit int) ([]domain.ContractIssuance, error)
}

// DocumentGenerator renders the contractual document (PDF).
type DocumentGenerator interface {
	Generate(ctx context.Context, data domain.ContractData) ([]byte, error)
}

// DocumentStore is the secure document repository. Documents are never
// overwritten with different content: each version has its own key.
type DocumentStore interface {
	Put(ctx context.Context, key string, content []byte, contentType string) error
	// Get returns ErrDocumentNotFound when the key is unknown.
	Get(ctx context.Context, key string) ([]byte, error)
}

// LinkSigner issues and checks the expiring links to a document.
type LinkSigner interface {
	Sign(policyID string, version int, expiresAt time.Time) string
	// Verify returns ErrInvalidLink unless the token is authentic and not expired.
	Verify(token string, now time.Time) (policyID string, version int, err error)
}

// Notifier tells the insured, through their configured contact channel, that
// the policy was issued.
type Notifier interface {
	Notify(ctx context.Context, n domain.IssuedNotification) error
}

// IssuanceAudit is the append-only record of the contractual issuance.
type IssuanceAudit interface {
	Record(ctx context.Context, e domain.IssuanceAuditEntry) error
	// List returns the entries of the policy, oldest first.
	List(ctx context.Context, policyID string) ([]domain.IssuanceAuditEntry, error)
}
